/*
Write a function positiveToNegative(number) that takes a number as an input parameter and if it is positive, 
converts it to a negative and returns the value.
*/

function positiveToNegative(number){
    if(number >= 0 || number >= 0){
        return -number;
    }else{
        return number;
    } 
}


console.log(positiveToNegative(4));
//result -4